-- Grassdoor initial operational schema
-- Creates the tables used by the browser app before later migrations extend them.

begin;

create table if not exists public.dim_pitches (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  area text,
  nearest_station text,
  game_format text,
  length numeric,
  width numeric,
  walls boolean not null default false,
  overhead_net boolean not null default false,
  men boolean not null default true,
  women boolean not null default true,
  under_18 boolean not null default true,
  showers boolean not null default false
);

create table if not exists public.fct_reviews (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  reviewer_name text,
  pitch_id bigint not null references public.dim_pitches(id) on delete cascade,
  quality_of_opposition integer not null,
  quality_of_pitch integer not null,
  price_per_team_per_game numeric(10,2) not null,
  overall_experience integer not null
);

alter table public.dim_pitches enable row level security;
alter table public.fct_reviews enable row level security;

drop policy if exists "public can read pitches" on public.dim_pitches;
create policy "public can read pitches"
on public.dim_pitches
for select
to anon, authenticated
using (true);

drop policy if exists "public can read reviews" on public.fct_reviews;
create policy "public can read reviews"
on public.fct_reviews
for select
to anon, authenticated
using (true);

drop policy if exists "public can submit reviews" on public.fct_reviews;
create policy "public can submit reviews"
on public.fct_reviews
for insert
to anon, authenticated
with check (true);

grant select on public.dim_pitches to anon, authenticated;
grant select, insert on public.fct_reviews to anon, authenticated;
grant usage, select on sequence public.dim_pitches_id_seq to anon, authenticated;
grant usage, select on sequence public.fct_reviews_id_seq to anon, authenticated;

commit;
